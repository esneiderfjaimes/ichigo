@Composable
private fun BaseIchigoThemePreview() {
    val colors = with(MaterialTheme.colorScheme) {
        listOf(
            primary to onPrimary and "primary",
            primaryContainer to onPrimaryContainer and "primaryContainer",
            secondary to onSecondary and "secondary",
            secondaryContainer to onSecondaryContainer and "secondaryContainer",
            tertiary to onTertiary and "tertiary",
            tertiaryContainer to onTertiaryContainer and "tertiaryContainer",
            error to onError and "error",
            errorContainer to onErrorContainer and "errorContainer",
            background to onBackground and "background",
            surface to onSurface and "surface",
            surfaceVariant to onSurfaceVariant and "surfaceVariant",
            outline to Color.Unspecified and "outline",
            outlineVariant to Color.Unspecified and "outlineVariant",
            inverseSurface to inverseOnSurface and "inverseSurface",
            inversePrimary to Color.Unspecified and "inversePrimary",
            surfaceDim to Color.Unspecified and "surfaceDim",
            surfaceBright to Color.Unspecified and "surfaceBright",
            surfaceContainerLowest to Color.Unspecified and "surfaceContainerLowest",
            surfaceContainerLow to Color.Unspecified and "surfaceContainerLow",
            surfaceContainer to Color.Unspecified and "surfaceContainer",
            surfaceContainerHigh to Color.Unspecified and "surfaceContainerHigh",
            surfaceContainerHighest to Color.Unspecified and "surfaceContainerHighest",
        )
    }
    FlowRow {
        colors.forEach { (color, onColor, name) ->
            // items(colors) { (color, onColor) ->
            Box(
                Modifier
                    .size(100.dp)
                    .background(color)
            ) {
                if (onColor != Color.Unspecified) {
                    Spacer(
                        Modifier
                            .clip(CircleShape)
                            .background(onColor)
                            .size(50.dp)
                            .align(Alignment.Center)
                    )
                }
                Text(
                    text = name.map { if (it.isUpperCase()) " ${it.lowercase()}" else it.toString() }
                        .joinToString(""),
                    modifier = Modifier.align(
                        if (onColor == Color.Unspecified) Alignment.Center
                        else Alignment.BottomCenter
                    ),
                    color = onColor,
                    fontSize = 10.sp,
                    textAlign = TextAlign.Center,
                    style = MaterialTheme.typography.bodySmall
                )
            }
        }
    }
}